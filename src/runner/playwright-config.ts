import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import type { QaConfig } from '../config/schema.js';
import type { QaPaths } from '../core/paths.js';

/**
 * Resolve the Playwright CLI from the same place `@company/ai-qa/playwright` resolves `@playwright/test`,
 * so the runner and the test files always share one Playwright copy.
 */
export function playwrightCli(): string {
  const require = createRequire(import.meta.url);
  return require.resolve('@playwright/test/cli');
}

/** Viewport names become both project names and test tags (`@desktop`, `@mobile`, ...). */
export function renderPlaywrightConfig(config: QaConfig): string {
  const projects = config.browsers.flatMap((browser) =>
    Object.entries(config.viewports).map(([name, vp]) => {
      const use: Record<string, unknown> = {
        browserName: browser,
        viewport: { width: vp.width, height: vp.height },
        deviceScaleFactor: 1,
      };
      if (vp.isMobile && browser === 'chromium') use.isMobile = true;
      if (vp.hasTouch) use.hasTouch = true;
      return `    { name: ${JSON.stringify(`${browser}-${name}`)}, grep: /@${name}\\b/, use: ${JSON.stringify(use)} },`;
    }),
  );
  return `// Generated by ai-qa on every run from .qa/config.ts — do not edit.
import { defineConfig } from '@company/ai-qa/playwright';

export default defineConfig({
  testDir: './tests',
  outputDir: process.env.AI_QA_OUTPUT_DIR ?? './artifacts/test-results',
  timeout: ${config.tests.timeoutMs},
  expect: { timeout: 5000 },
  retries: ${config.tests.verifyRetries},
  workers: ${config.tests.workers},
  fullyParallel: true,
  reporter: [['list'], ['json', { outputFile: process.env.AI_QA_JSON_REPORT ?? './artifacts/results.json' }]],
  use: {
    baseURL: ${JSON.stringify(config.app.baseUrl)},
    video: 'on',
    trace: 'on',
    screenshot: 'on',
  },
  projects: [
${projects.join('\n')}
  ],
});
`;
}

export function writePlaywrightConfig(paths: QaPaths, config: QaConfig): string {
  fs.mkdirSync(path.dirname(paths.playwrightConfig), { recursive: true });
  fs.writeFileSync(paths.playwrightConfig, renderPlaywrightConfig(config));
  return paths.playwrightConfig;
}
