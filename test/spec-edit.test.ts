import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import { describe, expect, it } from 'vitest';
import { listTestIds, removeTestBlock, tokenize, upsertTestBlock } from '../src/scenarios/spec-edit.js';

/** Syntax errors reported by the real TypeScript parser (devDependency, used only in tests). */
function syntaxErrors(code: string): string[] {
  const sf = ts.createSourceFile('x.spec.ts', code, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const diags = (sf as unknown as { parseDiagnostics: ts.Diagnostic[] }).parseDiagnostics;
  return diags.map((d) => ts.flattenDiagnosticMessageText(d.messageText, '\n'));
}

const SPEC = `// Generated by AI QA Agent from .qa/scenarios/checkout.json — regenerated when scenarios change.
import { test, expect, type Page } from '@mohammadvazifedoost/ai-qa-agent/playwright';

const total = (page: Page) => page.getByTestId('total');

/** Shared helper: opens checkout. */
async function open(page: Page) {
  await page.goto('/');
}

test('CHECKOUT-001: first', { tag: ['@functional'] }, async ({ page }) => {
  await open(page);
  await expect(total(page)).toHaveText('$60.00');
});

// Covers the coupon "SAVE10" path
test("CHECKOUT-002: it's got 'quotes' and (parens)", { tag: ['@functional'] }, async ({ page }) => {
  const s = ')}]"\\')'; // tricky: ) } ] in a string
  const t = \`total: \${String((1 + 2) * 3)} } ) \${'}'}\`;
  const re = /^\\(\\d+\\)[)}\\]]$/i;
  /* a block comment with ) and } */
  if (s.length > 0 / 2) {
    await expect(page.getByText(re)).toBeVisible();
  }
  await expect(total(page)).toHaveText(t);
});

test(\`CHECKOUT-003: template title\`, async ({ page }) => {
  await test.step('nested (step) {', async () => {
    await page.goto('/checkout');
  });
});

test.describe('group', () => {
  test('CHECKOUT-004: inside describe', async ({ page }) => {
    await page.goto('/');
  });

  test('CHECKOUT-005: also inside', async ({ page }) => {
    await page.goto('/');
  });
});

test.skip('CHECKOUT-006: skipped one', async () => {});
`;

describe('tokenize', () => {
  it('treats strings, templates, comments and regexes as single tokens', () => {
    const toks = tokenize("a('x)', `y ${b(')')} z`, /\\)/g) // c )\n/* ) */");
    expect(toks.map((t) => t.kind)).toEqual([
      'ident',
      'punct',
      'string',
      'punct',
      'template',
      'punct',
      'regex',
      'punct',
      'comment',
      'comment',
    ]);
  });

  it('distinguishes division from regex literals', () => {
    const kinds = tokenize('const x = (a) / 2 / b; const r = /2/;').map((t) => t.kind);
    expect(kinds.filter((k) => k === 'regex')).toHaveLength(1);
  });
});

describe('listTestIds', () => {
  it('finds test declarations including describe-nested and modifiers, not steps', () => {
    expect(listTestIds(SPEC)).toEqual([
      'CHECKOUT-001',
      'CHECKOUT-002',
      'CHECKOUT-003',
      'CHECKOUT-004',
      'CHECKOUT-005',
      'CHECKOUT-006',
    ]);
  });
});

describe('removeTestBlock', () => {
  it('parses cleanly before any edit', () => {
    expect(syntaxErrors(SPEC)).toEqual([]);
  });

  for (const id of [
    'CHECKOUT-001',
    'CHECKOUT-002',
    'CHECKOUT-003',
    'CHECKOUT-004',
    'CHECKOUT-005',
    'CHECKOUT-006',
  ]) {
    it(`removes only ${id} and leaves valid TypeScript`, () => {
      const { code, removed } = removeTestBlock(SPEC, id);
      expect(removed).toBe(1);
      expect(syntaxErrors(code)).toEqual([]);
      expect(listTestIds(code)).toEqual(listTestIds(SPEC).filter((x) => x !== id));
      expect(code).toContain('async function open(page: Page)');
      expect(code).toContain("import { test, expect, type Page } from '@mohammadvazifedoost/ai-qa-agent/playwright';");
      expect(code).not.toMatch(/\n\n\n/);
    });
  }

  it('removes the exact block text for a test with tricky strings, templates, regex and comments', () => {
    const { code } = removeTestBlock(SPEC, 'CHECKOUT-002');
    expect(code).not.toContain('tricky');
    expect(code).not.toContain('a block comment');
    expect(code).toContain("test('CHECKOUT-001: first'");
    expect(code).toContain('test(`CHECKOUT-003: template title`');
  });

  it('removes a detached leading comment that belongs to the test', () => {
    const { code } = removeTestBlock(SPEC, 'CHECKOUT-002');
    expect(code).not.toContain('Covers the coupon');
  });

  it('keeps comments that belong to a shared helper', () => {
    const src = `import { test } from 'x';

/** Opens the page. */
async function open() {}
test('A-001: one', async () => {});

test('A-002: two', async () => {});
`;
    const { code } = removeTestBlock(src, 'A-001');
    expect(code).toContain('/** Opens the page. */');
    expect(code).toContain('async function open() {}');
    expect(listTestIds(code)).toEqual(['A-002']);
  });

  it('keeps an attached comment that does not mention the id when code is directly above it', () => {
    const src = `const a = 1;
// about the constant above and the next test? ambiguous
test('A-001: one', async () => {});
`;
    const { code } = removeTestBlock(src, 'A-001');
    expect(code).toContain('ambiguous');
    expect(code).not.toContain('A-001');
  });

  it('removes an attached comment that names the id even without a blank line', () => {
    const src = `const a = 1;
// A-001 checks the thing
test('A-001: one', async () => {});
`;
    expect(removeTestBlock(src, 'A-001').code).toBe('const a = 1;\n');
  });

  it('never removes the generated file header', () => {
    const src = `// Generated by AI QA Agent from x
test('A-001: one', async () => {});
test('A-002: two', async () => {});
`;
    const { code } = removeTestBlock(src, 'A-001');
    expect(code.startsWith('// Generated by AI QA Agent')).toBe(true);
    expect(listTestIds(code)).toEqual(['A-002']);
  });

  it('does not match ids that are only a prefix or appear in steps', () => {
    const src = `test('A-0010: not me', async () => {});
test('B-001: other', async () => {
  await test.step('A-001: step title', async () => {});
});
`;
    expect(removeTestBlock(src, 'A-001')).toEqual({ code: src, removed: 0 });
  });

  it('handles CRLF line endings', () => {
    const src =
      "test('A-001: one', async () => {\r\n  const x = '}';\r\n});\r\n\r\ntest('A-002: two', async () => {});\r\n";
    const { code } = removeTestBlock(src, 'A-001');
    expect(code).toBe("test('A-002: two', async () => {});\r\n");
  });

  it('removes every declaration of a duplicated id', () => {
    const src = `test('A-001: one', async () => {});\n\ntest('A-001: again', async () => {});\n\ntest('A-002: two', async () => {});\n`;
    const { code, removed } = removeTestBlock(src, 'A-001');
    expect(removed).toBe(2);
    expect(code).toBe("test('A-002: two', async () => {});\n");
  });

  it('refuses a test that is not a standalone statement', () => {
    const src = `const t = test('A-001: one', async () => {});\n`;
    expect(() => removeTestBlock(src, 'A-001')).toThrow(/standalone/);
  });

  it('works on every test of the demo-shop fixture specs', () => {
    const dir = path.join(import.meta.dirname, '..', 'fixtures', 'demo-shop', '.qa', 'tests');
    for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.spec.ts'))) {
      const src = fs.readFileSync(path.join(dir, f), 'utf8');
      const ids = listTestIds(src);
      expect(ids.length, f).toBeGreaterThan(0);
      for (const id of ids) {
        const { code, removed } = removeTestBlock(src, id);
        expect(removed, `${f} ${id}`).toBe(1);
        expect(syntaxErrors(code), `${f} ${id}`).toEqual([]);
        expect(listTestIds(code), `${f} ${id}`).toEqual(ids.filter((x) => x !== id));
        expect(src.length - code.length, `${f} ${id}`).toBeLessThan(src.length / 2);
      }
    }
  });
});

describe('upsertTestBlock', () => {
  const FILE = `import { test, expect } from '@mohammadvazifedoost/ai-qa-agent/playwright';

test.describe('/checkout', () => {
  test('CHECKOUT-001: one', async ({ page }) => {
    await page.goto('/checkout');
  });

  // about two
  test('CHECKOUT-002: two', async ({ page }) => {
    await page.goto('/');
  });
});
`;
  const block = (id: string, body = "await page.goto('/new');") =>
    `test('${id}: fresh', async ({ page }) => {\n  ${body}\n});`;

  it('replaces the existing test in place, re-indented, keeping its comment and the other tests', () => {
    const res = upsertTestBlock(FILE, 'CHECKOUT-002', block('CHECKOUT-002'));
    expect(res.action).toBe('replaced');
    expect(res.code).toContain(`  // about two
  test('CHECKOUT-002: fresh', async ({ page }) => {
    await page.goto('/new');
  });
});`);
    expect(res.code).toContain("test('CHECKOUT-001: one'");
    expect(res.code).not.toContain("'CHECKOUT-002: two'");
    expect(syntaxErrors(res.code)).toEqual([]);
  });

  it('inserts a new test after the last one, inside the same describe block', () => {
    const res = upsertTestBlock(FILE, 'CHECKOUT-003', block('CHECKOUT-003'));
    expect(res.action).toBe('added');
    expect(res.code).toContain(`    await page.goto('/');
  });

  test('CHECKOUT-003: fresh', async ({ page }) => {
    await page.goto('/new');
  });
});`);
    expect(listTestIds(res.code)).toEqual(['CHECKOUT-001', 'CHECKOUT-002', 'CHECKOUT-003']);
    expect(syntaxErrors(res.code)).toEqual([]);
  });

  it('rejects a block that is not exactly one test for that id', () => {
    expect(() => upsertTestBlock(FILE, 'CHECKOUT-003', block('CHECKOUT-004'))).toThrow(/exactly one test/);
    expect(() =>
      upsertTestBlock(FILE, 'CHECKOUT-003', block('CHECKOUT-003') + '\n' + block('CHECKOUT-003')),
    ).toThrow(/exactly one test/);
    expect(() => upsertTestBlock(FILE, 'CHECKOUT-003', `${block('CHECKOUT-003')}\nconst x = 1;`)).toThrow(
      /only the test/,
    );
  });

  it('refuses a file without tests to anchor on', () => {
    expect(() => upsertTestBlock("import { test } from 'x';\n", 'A-001', block('A-001'))).toThrow(/no tests/);
  });
});
