const scenario = (id: string, title: string, extra: Partial<Scenario> = {}): Scenario => ({
  id,
  page: '/checkout',
  feature: 'checkout',
  category: 'functional',
  priority: 'medium',
  title,
  preconditions: [],
  steps: ['Open /checkout'],
  expectedResults: ['It works'],
  viewport: 'desktop',
  source: { figma: false, code: true },
  testData: [],
  design: null,
  rationale: 'why',
  approved: true,
  ...extra,
});

const page: AppModelFile['pages'][number] = {
  route: '/checkout',
  name: 'Checkout',
  purpose: 'pay',
  files: ['src/checkout.ts'],
  headings: [],
  interactiveElements: [],
  forms: [],
  states: { loading: null, empty: null, error: null },
  dataDependencies: [],
  preconditions: [],
  responsiveBehavior: [],
  businessRules: [],
} as unknown as AppModelFile['pages'][number];

const appModel = {
  summary: 's',
  pages: [page],
  flows: [],
  auth: null,
  stateManagement: 'none',
  testData: [],
  styling: { approach: 'css', tokens: {} },
  unknowns: [],
  analyzedAt: '2026-01-01T00:00:00.000Z',
  pageHashes: { '/checkout': 'h' },
  globalFileHashes: {},
};

const SPEC = `// Generated by AI QA Agent from .qa/scenarios/checkout.json — regenerated when scenarios change.
import { test, expect } from '@company/ai-qa-agent/playwright';

test('CHECKOUT-001: one', async ({ page }) => {
  await expect(page.getByText('(')).toBeVisible();
});

test('CHECKOUT-002: two', async ({ page }) => {
  await page.goto('/checkout');
});

test('CHECKOUT-003: three', async ({ page }) => {
  await page.goto('/checkout');
});
`;

function setup(
  scenarios = [
    scenario('CHECKOUT-001', 'One'),
    scenario('CHECKOUT-002', 'Two'),
    scenario('CHECKOUT-003', 'Three'),
  ],
) {
  const file: ScenarioFile = { page: '/checkout', generatedAt: 'x', inputHash: 'in', scenarios, removed: [] };
  const root = makeProject({
    '.qa/app-model.json': appModel,
    '.qa/scenarios/checkout.json': file,
    '.qa/tests/checkout.spec.ts': SPEC,
  });
  const paths = qaPaths(root);
  const state = new StateStore(paths.state);
  const ctx = {
    root,
    paths,
    state,
    config: { viewports: { desktop: { width: 1440, height: 900 } } },
  } as unknown as QaContext;
  // The spec is up to date with the current approved scenarios.
  state.data.generatedSpecs['tests/checkout.spec.ts'] = specHash(
    ctx,
    page,
    scenarios.filter((s) => s.approved),
  );
  const read = () =>
    ScenarioFileSchema.parse(
      JSON.parse(fs.readFileSync(path.join(paths.scenariosDir, 'checkout.json'), 'utf8')),
    );
  const spec = () => fs.readFileSync(path.join(paths.testsDir, 'checkout.spec.ts'), 'utf8');
  return { ctx, read, spec };
}

const ok: SpecValidator = async () => [];

describe('removeScenarios', () => {
  it('removes the scenario, its test and records a tombstone', async () => {
    const { ctx, read, spec } = setup();
    const validate = vi.fn(ok);
    const out = await removeScenarios(ctx, ['checkout-002'], { reason: 'duplicate', validate });
    expect(out).toEqual([
      {
        id: 'CHECKOUT-002',
        title: 'Two',
        page: '/checkout',
        spec: 'test-removed',
        specFile: '.qa/tests/checkout.spec.ts',
      },
    ]);
    expect(read().scenarios.map((s) => s.id)).toEqual(['CHECKOUT-001', 'CHECKOUT-003']);
    expect(read().removed).toMatchObject([{ id: 'CHECKOUT-002', title: 'Two', reason: 'duplicate' }]);
    expect(read().removed[0]!.scenario.title).toBe('Two');
    expect(read().inputHash).toBe('in');
    expect(listTestIds(spec())).toEqual(['CHECKOUT-001', 'CHECKOUT-003']);
    expect(validate).toHaveBeenCalledWith(ctx, expect.stringContaining('checkout.spec.ts'), [
      'CHECKOUT-001',
      'CHECKOUT-003',
    ]);
  });

  it('keeps the spec cache fresh so generate does not rewrite the file', async () => {
    const { ctx, read } = setup();
    await removeScenarios(ctx, ['CHECKOUT-002'], { validate: ok });
    const approved = read().scenarios.filter((s) => s.approved);
    expect(ctx.state.data.generatedSpecs['tests/checkout.spec.ts']).toBe(specHash(ctx, page, approved));
    // Persisted, not only in memory.
    expect(new StateStore(ctx.paths.state).data.generatedSpecs['tests/checkout.spec.ts']).toBe(
      specHash(ctx, page, approved),
    );
  });

  it('leaves a stale spec cache stale', async () => {
    const { ctx } = setup();
    ctx.state.data.generatedSpecs['tests/checkout.spec.ts'] = 'stale';
    await removeScenarios(ctx, ['CHECKOUT-002'], { validate: ok });
    expect(ctx.state.data.generatedSpecs['tests/checkout.spec.ts']).toBe('stale');
  });

  it('restores the spec and changes nothing when validation fails', async () => {
    const { ctx, read, spec } = setup();
    await expect(
      removeScenarios(ctx, ['CHECKOUT-002'], {
        validate: async () => ['Playwright could not load the file'],
      }),
    ).rejects.toThrow(/nothing was changed/);
    expect(spec()).toBe(SPEC);
    expect(read().scenarios).toHaveLength(3);
    expect(read().removed).toEqual([]);
  });

  it('rejects unknown and already removed ids before touching anything', async () => {
    const { ctx, spec } = setup();
    await expect(removeScenarios(ctx, ['CHECKOUT-001', 'CHECKOUT-099'], { validate: ok })).rejects.toThrow(
      /Unknown scenario CHECKOUT-099/,
    );
    expect(spec()).toBe(SPEC);
    await removeScenarios(ctx, ['CHECKOUT-001'], { validate: ok });
    await expect(removeScenarios(ctx, ['CHECKOUT-001'], { validate: ok })).rejects.toThrow(/already removed/);
  });

  it('removes several ids at once and handles scenarios without a test', async () => {
    const { ctx, read, spec } = setup([
      scenario('CHECKOUT-001', 'One'),
      scenario('CHECKOUT-002', 'Two'),
      scenario('CHECKOUT-003', 'Three'),
      scenario('CHECKOUT-004', 'Unapproved', { approved: false }),
    ]);
    const out = await removeScenarios(ctx, ['CHECKOUT-001', 'CHECKOUT-004'], { validate: ok });
    expect(out.map((o) => [o.id, o.spec])).toEqual([
      ['CHECKOUT-001', 'test-removed'],
      ['CHECKOUT-004', 'no-test'],
    ]);
    expect(listTestIds(spec())).toEqual(['CHECKOUT-002', 'CHECKOUT-003']);
    expect(read().removed.map((r) => r.id)).toEqual(['CHECKOUT-001', 'CHECKOUT-004']);
  });
});

describe('restoreScenarios', () => {
  it('puts the scenario back approved, in id order, and drops the tombstone', async () => {
    const { ctx, read, spec } = setup([
      scenario('CHECKOUT-001', 'One'),
      scenario('CHECKOUT-002', 'Two', { approved: false }),
      scenario('CHECKOUT-003', 'Three'),
    ]);
    await removeScenarios(ctx, ['CHECKOUT-002'], { validate: ok });
    const specAfterRemove = spec();
    expect(restoreScenarios(ctx, ['checkout-002'])).toEqual([
      { id: 'CHECKOUT-002', title: 'Two', page: '/checkout' },
    ]);
    expect(read().scenarios.map((s) => [s.id, s.approved])).toEqual([
      ['CHECKOUT-001', true],
      ['CHECKOUT-002', true],
      ['CHECKOUT-003', true],
    ]);
    expect(read().removed).toEqual([]);
    // The test comes back through `generate`: the spec is untouched and its cache is now stale.
    expect(spec()).toBe(specAfterRemove);
    const approved = read().scenarios.filter((s) => s.approved);
    expect(ctx.state.data.generatedSpecs['tests/checkout.spec.ts']).not.toBe(specHash(ctx, page, approved));
  });

  it('rejects ids that are not removed', () => {
    const { ctx } = setup();
    expect(() => restoreScenarios(ctx, ['CHECKOUT-001'])).toThrow(/is not removed/);
    expect(() => restoreScenarios(ctx, ['CHECKOUT-042'])).toThrow(/No removed scenario/);
  });
});

describe('listScenarioRows / formatScenarioTable', () => {
  it('lists active scenarios with their latest status, and removed ones on request', async () => {
    const { ctx } = setup([
      scenario('CHECKOUT-001', 'One'),
      scenario('CHECKOUT-002', 'Two', { approved: false }),
    ]);
    await removeScenarios(ctx, ['CHECKOUT-001'], { validate: ok });
    expect(listScenarioRows(ctx, { page: 'checkout' })).toEqual([
      { id: 'CHECKOUT-002', category: 'functional', page: '/checkout', title: 'Two', status: 'unapproved' },
    ]);
    expect(listScenarioRows(ctx, { removed: true }).map((r) => [r.id, r.status])).toEqual([
      ['CHECKOUT-001', 'removed'],
      ['CHECKOUT-002', 'unapproved'],
    ]);
    expect(() => listScenarioRows(ctx, { page: 'login' })).toThrow(/No scenarios for page/);
  });

  it('uses the latest run results for the status', () => {
    const { ctx } = setup([scenario('CHECKOUT-001', 'One'), scenario('CHECKOUT-002', 'Two')]);
    const run = ctx.state.startRun({});
    const outcome = (scenarioId: string, status: TestOutcome['status'], project: string): TestOutcome => ({
      key: `${scenarioId}_${project}`,
      scenarioId,
      title: scenarioId,
      file: 'checkout.spec.ts',
      line: 1,
      project,
      tags: [],
      status,
      attempts: 1,
      durationMs: 1,
      error: null,
      annotations: [],
      artifacts: { video: null, trace: null, screenshots: [], errorContext: null, logs: null, design: [] },
    });
    const dir = path.join(ctx.paths.artifactsDir, 'runs', run.id);
    fs.mkdirSync(dir, { recursive: true });
    const results: TestRunResult = {
      runId: run.id,
      runDir: dir,
      outcomes: [outcome('CHECKOUT-001', 'passed', 'a'), outcome('CHECKOUT-001', 'failed', 'b')],
      globalErrors: [],
      exitCode: 1,
      stats: { passed: 1, failed: 1, flaky: 0, skipped: 0 },
    };
    fs.writeFileSync(path.join(dir, 'results.json'), JSON.stringify(results));
    expect(listScenarioRows(ctx).map((r) => [r.id, r.status])).toEqual([
      ['CHECKOUT-001', 'failed'],
      ['CHECKOUT-002', 'not run'],
    ]);
  });

  it('formats aligned columns with the title last', () => {
    const lines = formatScenarioTable([
      { id: 'CHECKOUT-001', category: 'functional', page: '/checkout', title: 'One', status: 'passed' },
      { id: 'HOME-010', category: 'visual', page: '/', title: 'Two', status: 'not run' },
    ]);
    expect(lines).toEqual([
      'ID            TYPE        PAGE       STATUS   TITLE',
      'CHECKOUT-001  functional  /checkout  passed   One',
      'HOME-010      visual      /          not run  Two',
    ]);
  });

  it('normalizes ids', () => {
    expect(normalizeId(' checkout-008 ')).toBe('CHECKOUT-008');
  });
});

describe('scenario generation with tombstones', () => {
  it('tells the AI about removed scenarios and drops them if returned anyway', async () => {
    const { ctx, read } = setup([scenario('CHECKOUT-001', 'One'), scenario('CHECKOUT-002', 'Two')]);
    await removeScenarios(ctx, ['CHECKOUT-002'], { reason: 'flaky by design', validate: ok });
    let prompt = '';
    (ctx as { ai: unknown }).ai = {
      run: async (task: { prompt: string }) => {
        prompt = task.prompt;
        return {
          output: {
            scenarios: [
              scenario('CHECKOUT-001', 'One'),
              scenario('CHECKOUT-002', 'Something new'), // removed id reused
              scenario('CHECKOUT-003', '  two  '), // removed title under a new id
              scenario('CHECKOUT-004', 'Four'),
            ],
          },
        };
      },
    };
    await generateScenarios(ctx, { force: true });
    expect(prompt).toContain('## Removed scenarios — DO NOT recreate');
    expect(prompt).toContain('- CHECKOUT-002: Two (reason: flaky by design)');
    expect(read().scenarios.map((s) => s.id)).toEqual(['CHECKOUT-001', 'CHECKOUT-004']);
    expect(read().removed.map((r) => r.id)).toEqual(['CHECKOUT-002']);
  });

  it('adds no prompt section when nothing was removed', () => {
    expect(removedSection([])).toBe('');
  });

  it('dropRemoved keeps unrelated scenarios', () => {
    const kept = dropRemoved(
      [scenario('A-001', 'Keep'), scenario('A-002', 'Gone')],
      [{ id: 'A-002', title: 'Gone', removedAt: 'x', scenario: scenario('A-002', 'Gone') }],
    );
    expect(kept.map((s) => s.id)).toEqual(['A-001']);
  });
});
